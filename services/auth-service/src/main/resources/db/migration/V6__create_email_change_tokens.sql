-- =====================================================================
-- V6 - Tokens de cambio de email de login
--
-- Igual que en password_reset_tokens y refresh_tokens, se guarda solo
-- el hash SHA-256 del token opaco: el valor crudo viaja una vez en el
-- enlace enviado al email actual y nunca toca la base.
-- =====================================================================
create table public.email_change_tokens (
  id         bigint generated by default as identity primary key,
  user_id    bigint      not null references public.users(id) on delete cascade,
  token_hash text        not null unique,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);

create index idx_email_change_tokens_user on public.email_change_tokens (user_id);
