-- =====================================================================
-- V3 - Tokens de recuperacion de contrasena
--
-- Va como V3 porque V2 es el seed de desarrollo que vive en db/seed.
-- Igual que en refresh_tokens, se guarda solo el hash SHA-256: el valor
-- crudo viaja una vez en el correo y nunca toca la base.
-- =====================================================================
create table public.password_reset_tokens (
  id         bigint generated by default as identity primary key,
  user_id    bigint      not null references public.users(id) on delete cascade,
  token_hash text        not null unique,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);

create index idx_password_reset_tokens_user on public.password_reset_tokens (user_id);
