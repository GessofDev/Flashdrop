-- Entrega con código de verificación.
--   reception_mode              : NORMAL (código fijo 000000) o SEGURO (código único del cliente).
--   delivery_code_version       : número del código vigente (1 = original, 2 = renovado).
--                                 El código NO se guarda: se deriva de (pedido, versión) con una
--                                 clave secreta del servicio.
--   delivery_code_attempts      : intentos fallidos sobre el código vigente.
--   delivery_code_verified_at   : cuándo se confirmó la entrega con el código.
-- Los pedidos existentes quedan en modo NORMAL, sin cambio de comportamiento.
ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS reception_mode            varchar(10) NOT NULL DEFAULT 'NORMAL',
    ADD COLUMN IF NOT EXISTS delivery_code_version     integer     NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS delivery_code_attempts    integer     NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS delivery_code_verified_at timestamptz;

ALTER TABLE public.orders
    DROP CONSTRAINT IF EXISTS chk_orders_reception_mode;

ALTER TABLE public.orders
    ADD CONSTRAINT chk_orders_reception_mode CHECK (reception_mode IN ('NORMAL', 'SEGURO'));

-- Bitácora de intentos de entrega (aciertos y fallos). Nunca guarda el código ingresado.
CREATE TABLE IF NOT EXISTS public.order_delivery_code_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     bigint      NOT NULL,
  delivery_id  bigint,
  code_version integer     NOT NULL,
  success      boolean     NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fk_delivery_code_attempts_order FOREIGN KEY (order_id) REFERENCES public.orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_delivery_code_attempts_order ON public.order_delivery_code_attempts(order_id);
