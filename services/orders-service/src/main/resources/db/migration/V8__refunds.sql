-- =====================================================================
-- V8 - Libro de reembolsos (FlashDrop 1.0 tiendas, spec 4.1)
--
-- Un reembolso puede ser TOTAL o PARCIAL (refund_type): segun el caso se devuelve todo o la
-- parte que corresponda. Un pago puede tener varios reembolsos PARCIALES, pero a lo mas uno
-- TOTAL. Que la suma de los reembolsos no supere lo cobrado la valida la aplicacion (depende
-- del monto del pago, que esta en otra tabla).
--
-- refund_key es la llave de idempotencia que se envia a la pasarela: reintentar nunca
-- devuelve dos veces. Un reintento reutiliza la misma fila (attempts sube).
-- next_attempt_at guarda la espera creciente entre reintentos.
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.refunds (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id         bigint        NOT NULL,
  order_id           bigint        NOT NULL,
  refund_type        varchar(10)   NOT NULL DEFAULT 'TOTAL',
  amount             numeric(12,2) NOT NULL CHECK (amount > 0),
  reason             varchar(20)   NOT NULL,
  status             varchar(10)   NOT NULL DEFAULT 'PENDIENTE',
  attempts           integer       NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at    timestamptz,
  refund_key         varchar(64)   NOT NULL,
  provider_refund_id varchar(100),
  last_error         varchar(500),
  created_at         timestamptz   NOT NULL DEFAULT now(),
  updated_at         timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id) REFERENCES public.payments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_refunds_order   FOREIGN KEY (order_id)   REFERENCES public.orders(id)   ON DELETE RESTRICT,
  CONSTRAINT chk_refunds_type   CHECK (refund_type IN ('TOTAL', 'PARCIAL')),
  CONSTRAINT chk_refunds_reason CHECK (reason IN
      ('RECHAZO', 'CANCELACION', 'VENCIMIENTO', 'F17', 'F18', 'CLIENTE_AUSENTE')),
  CONSTRAINT chk_refunds_status CHECK (status IN ('PENDIENTE', 'HECHO', 'FALLIDO')),
  CONSTRAINT uq_refunds_key     UNIQUE (refund_key)
);

CREATE INDEX IF NOT EXISTS idx_refunds_order   ON public.refunds(order_id);
CREATE INDEX IF NOT EXISTS idx_refunds_payment ON public.refunds(payment_id);
-- A lo mas un reembolso TOTAL por pago (los parciales pueden ser varios).
CREATE UNIQUE INDEX IF NOT EXISTS uq_refunds_one_total
    ON public.refunds(payment_id) WHERE refund_type = 'TOTAL';
-- Soporte de la tarea de reintentos: solo los reembolsos que aun no terminaron.
CREATE INDEX IF NOT EXISTS idx_refunds_retry
    ON public.refunds(status, next_attempt_at) WHERE status <> 'HECHO';
