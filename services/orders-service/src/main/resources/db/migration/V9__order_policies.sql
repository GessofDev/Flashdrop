-- =====================================================================
-- V9 - Politicas parametricas del pedido (FlashDrop 1.0 tiendas, spec 4.1)
--
-- Los plazos NO van en el codigo ni en variables de entorno fijas: los define el
-- administrador (valores globales) y cada tienda puede ajustar los suyos.
--
--   payment_expiration_minutes     : plazo para pagar un pedido.
--   store_response_minutes         : plazo para que la tienda acepte un pedido pagado.
--   customer_cancel_window_minutes : minutos, desde la compra, en que el cliente puede
--                                    cancelar. 0 = no puede cancelar. Pasado ese plazo (o
--                                    una vez retirado el producto) el pedido se cobra igual.
--
-- restaurant_id NULL = fila global (exactamente una, con los tres valores). Una fila de tienda
-- puede dejar cualquier campo en NULL: ese campo hereda el valor global.
-- Los endpoints para editarlas (admin / dueno de la tienda) son un cambio posterior.
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.order_policies (
  id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id                  bigint,
  payment_expiration_minutes     integer     CHECK (payment_expiration_minutes     BETWEEN 1 AND 1440),
  store_response_minutes         integer     CHECK (store_response_minutes         BETWEEN 1 AND 1440),
  customer_cancel_window_minutes integer     CHECK (customer_cancel_window_minutes BETWEEN 0 AND 1440),
  updated_by_user_id             bigint,
  created_at                     timestamptz NOT NULL DEFAULT now(),
  updated_at                     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_order_policies_global_complete CHECK (
      restaurant_id IS NOT NULL
      OR (payment_expiration_minutes IS NOT NULL
          AND store_response_minutes IS NOT NULL
          AND customer_cancel_window_minutes IS NOT NULL))
);

-- Una fila por tienda (restaurant_id es ref. externa a Catalog, sin FK) y una sola global.
CREATE UNIQUE INDEX IF NOT EXISTS uq_order_policies_restaurant
    ON public.order_policies(restaurant_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_order_policies_global
    ON public.order_policies((1)) WHERE restaurant_id IS NULL;

-- Valores iniciales propuestos; el administrador los cambia sin desplegar.
INSERT INTO public.order_policies
    (restaurant_id, payment_expiration_minutes, store_response_minutes, customer_cancel_window_minutes)
SELECT NULL, 15, 10, 5
WHERE NOT EXISTS (SELECT 1 FROM public.order_policies WHERE restaurant_id IS NULL);
