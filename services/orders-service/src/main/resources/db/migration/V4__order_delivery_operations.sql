-- Bitácora durable de operaciones sobre pedidos en delivery (liberación y anulación post-retiro)
CREATE TABLE IF NOT EXISTS public.order_delivery_operations (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id              bigint NOT NULL,
  operation_type        text NOT NULL,
  state                 text NOT NULL,
  actor_user_id         bigint NOT NULL,
  actor_role            text NOT NULL,
  reason                varchar(500) NOT NULL,
  target_status         text,
  previous_delivery_id  bigint,
  resulting_delivery_id bigint,
  previous_status       text,
  resulting_status      text,
  correlation_id        text,
  failure_code          text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fk_delivery_operations_order FOREIGN KEY (order_id) REFERENCES public.orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_order_delivery_operations_order ON public.order_delivery_operations(order_id);
CREATE INDEX IF NOT EXISTS idx_order_delivery_operations_state ON public.order_delivery_operations(state, created_at);
