-- Tarifa de envio parametrizable (F8). El administrador carga dos tablas: el costo por dimension
-- del pedido (que tambien fija el vehiculo) y el costo por distancia. El envio es la suma.
-- Sin filas no hay tarifa y Orders cobra el envio de respaldo (orders.delivery-fee).

CREATE TABLE IF NOT EXISTS public.delivery_tariff_dimension_ranges (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  min_dimension      integer       NOT NULL CHECK (min_dimension >= 0),
  max_dimension      integer       CHECK (max_dimension IS NULL OR max_dimension >= min_dimension),
  vehicle            varchar(10)   NOT NULL CHECK (vehicle IN ('MOTO', 'BICI', 'AUTO')),
  price              numeric(12,2) NOT NULL CHECK (price >= 0),
  updated_by_user_id bigint,
  updated_at         timestamptz   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_tariff_dimension_min
    ON public.delivery_tariff_dimension_ranges(min_dimension);

CREATE TABLE IF NOT EXISTS public.delivery_tariff_distance_ranges (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  min_km             numeric(7,2)  NOT NULL CHECK (min_km >= 0),
  max_km             numeric(7,2)  CHECK (max_km IS NULL OR max_km > min_km),
  price              numeric(12,2) NOT NULL CHECK (price >= 0),
  updated_by_user_id bigint,
  updated_at         timestamptz   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_tariff_distance_min
    ON public.delivery_tariff_distance_ranges(min_km);
