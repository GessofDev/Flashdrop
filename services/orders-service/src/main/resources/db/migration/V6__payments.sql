-- =====================================================================
-- V6 - Libro de pagos (FlashDrop 1.0 tiendas, spec 4.1)
--
-- Cada intento de cobro de un pedido es una fila. Un pedido puede tener varios intentos
-- (uno rechazado y luego uno aprobado), pero NUNCA dos cobros aprobados ni dos abiertos a la
-- vez: lo garantizan los indices parciales de abajo, no solo el codigo (defensa contra el
-- doble cobro cuando el webhook y la tarea de vencimiento llegan al mismo tiempo).
--
-- provider es texto libre (fake | webpay | mercadopago | flow): elegir pasarela no requiere
-- una migracion. Migracion aditiva: la version anterior del servicio ignora esta tabla.
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.payments (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       bigint        NOT NULL,
  provider       varchar(30)   NOT NULL,
  provider_tx_id varchar(100)  NOT NULL,
  amount         numeric(12,2) NOT NULL CHECK (amount > 0),
  currency       char(3)       NOT NULL DEFAULT 'CLP',
  status         varchar(12)   NOT NULL DEFAULT 'PENDIENTE',
  raw_status     varchar(100),
  created_at     timestamptz   NOT NULL DEFAULT now(),
  updated_at     timestamptz   NOT NULL DEFAULT now(),
  -- RESTRICT (los hijos de orders usan CASCADE): un registro de dinero no desaparece
  -- por borrar un pedido.
  CONSTRAINT fk_payments_order   FOREIGN KEY (order_id) REFERENCES public.orders(id) ON DELETE RESTRICT,
  CONSTRAINT chk_payments_status CHECK (status IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'EXPIRADO')),
  -- provider + tx: dos pasarelas distintas podrian repetir un identificador.
  CONSTRAINT uq_payments_provider_tx UNIQUE (provider, provider_tx_id)
);

CREATE INDEX IF NOT EXISTS idx_payments_order ON public.payments(order_id);

-- Una sola transaccion abierta y un solo pago aprobado por pedido.
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_one_pending
    ON public.payments(order_id) WHERE status = 'PENDIENTE';
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_one_approved
    ON public.payments(order_id) WHERE status = 'APROBADO';
