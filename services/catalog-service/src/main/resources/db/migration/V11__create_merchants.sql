create table public.merchants (
    id          bigint generated by default as identity primary key,
    name        varchar(255) not null,
    legal_name  varchar(255),
    tax_id      varchar(64),
    phone       varchar(32),
    email       varchar(255),
    status      varchar(16) not null default 'ACTIVO',
    created_at  timestamp(6) not null default current_timestamp,
    updated_at  timestamp(6) not null default current_timestamp
);
create index idx_merchants_name on public.merchants(name);

create table public.merchant_members (
    id          bigint generated by default as identity primary key,
    merchant_id bigint not null references public.merchants(id) on delete cascade,
    user_id     bigint not null,
    role        varchar(16) not null default 'DUEÑO',
    created_at  timestamp(6) not null default current_timestamp,
    constraint uq_merchant_member unique (merchant_id, user_id)
);
create index idx_merchant_members_user on public.merchant_members(user_id);
